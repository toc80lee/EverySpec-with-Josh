export function presetToAlvField(preset: SapDictionaryPreset, nextPos: number): AlvField {
  return {
    id: `fld-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    col_pos: nextPos,
    fieldname: preset.field,
    coltext: preset.label,
    scrtext_s: preset.label.slice(0, 10),
    scrtext_m: preset.label.slice(0, 20),
    scrtext_l: preset.label.slice(0, 40),
    datatype: preset.type,
    outputlen: preset.length,
    just: preset.just,
    key: preset.field === 'VBELN' || preset.field === 'EBELN' || preset.field === 'BELNR' || preset.field === 'MATNR',
    hotspot: !!preset.hotspot,
    checkbox: preset.field === 'CHECKBOX',
    edit: false,
    do_sum: preset.type === 'CURR' || preset.type === 'DEC',
    emphasize: preset.field === 'LIGHTS' ? '' : (preset.field === 'VBELN' || preset.field === 'EBELN' || preset.field === 'BELNR' ? 'C100' : ''),
    cfieldname: preset.type === 'CURR' ? (preset.module === 'SD' ? 'WAERK' : 'WAERS') : undefined,
    qfieldname: preset.type === 'DEC' ? 'MEINS' : undefined,
    ref_table: preset.table,
    ref_field: preset.field,
    drilldown_tcode: preset.drilldown_tcode,
  };
}
